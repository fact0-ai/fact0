// renderPDF builds an audit report with verification results, recorded events
// and an explicit explanation of the evidence limitations.
func renderPDF(ctx context.Context, w io.Writer, svc *Service, in PDFInput) error {
	if in.From.IsZero() {
		in.From = historyStart
	}
	if in.To.IsZero() {
		in.To = farFuture
	}
	if in.VerifyURL == "" {
		in.VerifyURL = "/v1/verify"
	}

	// Use VerifyDeep so the PDF shows every broken event, not just the first.
	verify, err := svc.VerifyDeep(ctx, in.TenantID, in.From, in.To)
	if err != nil {
		return fmt.Errorf("computing chain verification: %w", err)
	}

	// Build a set of broken event IDs for O(1) row-colouring in the event log.
	brokenSet := make(map[string]BrokenEvent, len(verify.AllBrokenEvents))
	for _, b := range verify.AllBrokenEvents {
		brokenSet[b.EventID] = b
	}

	actionCounts, err := svc.repo.CountByAction(ctx, in.TenantID, in.From, in.To)
	if err != nil {
		return fmt.Errorf("counting by action: %w", err)
	}
	actorCounts, err := svc.repo.CountByActorType(ctx, in.TenantID, in.From, in.To)
	if err != nil {
		return fmt.Errorf("counting by actor type: %w", err)
	}

	pdf := gofpdf.New("P", "mm", "A4", "")
	pdf.SetMargins(15, 15, 15)
	pdf.SetAutoPageBreak(true, 20)
	pdf.SetFooterFunc(func() {
		pdf.SetY(-15)
		pdf.SetFont("Arial", "I", 8)
		pdf.SetTextColor(120, 120, 120)
		pdf.CellFormat(0, 8,
			fmt.Sprintf("Generated by Fact0 Audit. Verify integrity at %s    Page %d of {nb}",
				in.VerifyURL, pdf.PageNo()),
			"", 0, "C", false, 0, "")
	})
	pdf.AliasNbPages("")

	renderCover(pdf, in, verify)
	renderTamperEvidence(pdf, in, verify)
	renderSummaries(pdf, actionCounts, actorCounts)
	if err := renderEventLog(ctx, pdf, svc, in, brokenSet); err != nil {
		return err
	}
	renderLimitationsAppendix(pdf)

	if err := pdf.Output(w); err != nil {
		return fmt.Errorf("writing pdf: %w", err)
	}
	return nil
}

